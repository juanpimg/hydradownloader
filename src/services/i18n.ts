const dicts: Record<Locale, Record<I18nKey, string>> = { en, es, fr, de, pt, it };

let current: Locale = 'en';

export function setLocale(locale: Locale): void {
  current = locale;
}

export function getLocale(): Locale {
  return current;
}

/** Resolve a stored preference to a concrete locale using the browser language. */
export function resolveLocale(
  preference: LocalePreference,
  browserLanguage?: string
): Locale {
  if (preference !== 'system') return preference;
  const lang = (
    browserLanguage ??
    (typeof navigator !== 'undefined' ? navigator.language : 'en')
  ).toLowerCase();
  const match = SUPPORTED_LOCALES.find((l) => l !== 'en' && lang.startsWith(l));
  return match ?? 'en';
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const dict = dicts[current] ?? en;
  let out: string = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(`{${k}}`, String(v));
    }
  }
  return out;
}
